// Nombre completo "Nombre, detalle" en inglés.
export const nameEn = (full) => {
  const i = full.indexOf(','); const base = i < 0 ? full : full.slice(0, i); const detail = i < 0 ? '' : full.slice(i + 1).trim();
  const m = base.match(/^Menú (\d+)$/);
  const b = m ? `Set Menu ${m[1]}` : (names[base] ?? base);
  const d = detail.replace(/(\d+) unidades/, '$1 pieces').replace(/(\d+) unidad$/, '$1 piece').replace(/(\d+) piezas/, '$1 pieces').replace(/^lata (\d+ ml)$/, '$1 can').replace(/^botella$/, 'bottle').replace(/^pequeño$/, 'small').replace(/^grande$/, 'large');
  return d ? `${b}, ${d}` : b;
};
